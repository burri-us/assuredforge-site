// Generates the site's design tokens from design/tokens.json (a copy of the Tierra design system's tokens.json) and ships the
// self-hosted brand faces. Runs at the start of every build (npm run build, npm run dev).
//   Writes: styles/tokens.generated.css  CSS custom properties (Tailwind theme), @font-face rules
//           components/tokens.generated.ts  values TypeScript needs (theme colour)
//           components/notices.generated.json  licence texts of the fonts (third-party notices page)
//           styles/fonts/*.woff2  copied from the pinned @fontsource packages (never a CDN)
//   Fails if design/tokens.json no longer matches the SHA-256 in design/tokens.sha256 (change the pin on purpose, see README).
// Never type a colour, size or font by hand elsewhere: scripts/check-tokens.mjs fails the build on that.
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";

const root = new URL("../", import.meta.url);
const read = (p) => readFileSync(new URL(p, root), "utf8");
const write = (p, s) => writeFileSync(new URL(p, root), s);

const raw = readFileSync(new URL("design/tokens.json", root));
const sha = createHash("sha256").update(raw).digest("hex");
const pinned = read("design/tokens.sha256").trim().split(/\s+/)[0];
if (sha !== pinned) {
  console.error(`design/tokens.json SHA-256 ${sha} does not match design/tokens.sha256 (${pinned}).`);
  process.exit(1);
}
const t = JSON.parse(raw.toString("utf8"));

const byName = Object.fromEntries(t.color.tokens.map((c) => [c.name, c]));
const val = (c, theme) => {
  let v = c.value;
  if (typeof v === "string") { const m = /^\{(.+)\}$/.exec(v); return val(byName[m[1]], theme); }
  return v[theme];
};

const light = t.color.tokens.map((c) => `  --color-${c.name}: ${val(c, "light")};`).join("\n");
const dark = t.color.tokens.map((c) => `    --color-${c.name}: ${val(c, "dark")};`).join("\n");
const fam = Object.entries(t.type.families).map(([k, v]) => `  --font-${k}: ${v};`).join("\n");
const styles = t.type.groups.flatMap((g) => g.styles.map((s) => ({ ...s, family: g.family })));
const text = styles.map((s) => [
  `  --text-${s.name}: ${s.fontSize};`,
  `  --text-${s.name}--line-height: ${s.lineHeight};`,
  `  --text-${s.name}--font-weight: ${s.fontWeight};`,
  s.letterSpacing ? `  --text-${s.name}--letter-spacing: ${s.letterSpacing};` : "",
].filter(Boolean).join("\n")).join("\n");
const space = t.spacing.tokens.map((s) => `  --${s.name}: ${s.value};`).join("\n");
const radius = t.radius.tokens.map((s) => `  --${s.name}: ${s.value};`).join("\n");
const size = t.size.tokens.map((s) => `  --${s.name}: ${s.value};`).join("\n");
const shadow = t.shadow.tokens.map((s) => `  --${s.name}: ${s.value};`).join("\n");

// Faces and weights the site uses (latin subset), from the pinned packages; weights follow tokens.json (400, 600, 700).
const FACES = [
  ["Inter", "inter", "inter", [400, 600]],
  ["Space Grotesk", "space-grotesk", "space-grotesk", [600, 700]],
  ["JetBrains Mono", "jetbrains-mono", "jetbrains-mono", [400]],
];
mkdirSync(new URL("styles/fonts/", root), { recursive: true });
const faces = [];
const notices = [];
for (const [family, pkg, file, weights] of FACES) {
  const pj = JSON.parse(read(`node_modules/@fontsource/${pkg}/package.json`));
  for (const w of weights) {
    const f = `${file}-latin-${w}-normal.woff2`;
    copyFileSync(new URL(`node_modules/@fontsource/${pkg}/files/${f}`, root), new URL(`styles/fonts/${f}`, root));
    faces.push(`@font-face {\n  font-family: "${family}";\n  font-style: normal;\n  font-display: swap;\n  font-weight: ${w};\n  src: url("./fonts/${f}") format("woff2");\n}`);
  }
  notices.push({ family, package: `@fontsource/${pkg}`, version: pj.version, license: "SIL Open Font License 1.1", text: read(`node_modules/@fontsource/${pkg}/LICENSE`).trim() });
}

write("styles/tokens.generated.css",
`/* GENERATED by scripts/tokens.mjs from design/tokens.json (SHA-256 ${sha}). Do not edit. */
${faces.join("\n")}

@theme {
${light}
${fam}
${text}
${radius}
${shadow}
}

:root {
${space}
${size}
}

@media (prefers-color-scheme: dark) {
  :root {
${dark}
  }
}
`);
write("components/tokens.generated.ts",
`// GENERATED by scripts/tokens.mjs from design/tokens.json (SHA-256 ${sha}). Do not edit.
export const themeColor = ${JSON.stringify(val(byName.ink, "light"))};
`);
write("components/notices.generated.json", JSON.stringify(notices, null, 2) + "\n");
console.log(`tokens: generated from design/tokens.json ${sha.slice(0, 12)}`);
